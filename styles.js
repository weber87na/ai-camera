/**
 * 判斷指定風格是否需要強制卡通化。
 *
 * @param {string} styleId
 * @returns {boolean}
 */
export function isCartoonStyle(styleId) {
  return CARTOON_STYLE_IDS.includes(styleId);
}

/**
 * 判斷指定風格是否需要強制三維渲染。
 *
 * @param {string} styleId
 * @returns {boolean}
 */
export function isThreeDStyle(styleId) {
  return THREE_D_STYLE_IDS.includes(styleId);
}

/**
 * 檢查 styleId 是否為後端允許的風格。
 *
 * @param {string} styleId
 * @returns {boolean}
 */
export function isAllowedStyle(styleId) {
  if (typeof styleId !== "string") {
    return false;
  }

  return Object.prototype.hasOwnProperty.call(
    STYLE_PROMPTS,
    styleId
  );
}

/**
 * 取得完整提示詞。
 *
 * 場景保留規則會放在最後，避免風格提示詞覆蓋原始場景。
 *
 * @param {string} styleId
 * @returns {string|null}
 */
export function getStylePrompt(styleId) {
  if (!isAllowedStyle(styleId)) {
    return null;
  }

  const sections = [
    BASE_PROMPT,
    `指定的視覺風格：${STYLE_LABELS[styleId]}`,
    STYLE_PROMPTS[styleId]
  ];

  if (isCartoonStyle(styleId)) {
    sections.push(CARTOON_FACE_ENFORCER);
  }

  if (isThreeDStyle(styleId)) {
    sections.push(THREE_D_STYLE_ENFORCER);
  }

  // 必須放在最後，強化原始場景保留要求。
  sections.push(SCENE_PRESERVATION_ENFORCER);

  return sections.join("\n\n");
}

/**
 * 取得風格中文名稱。
 *
 * @param {string} styleId
 * @returns {string|null}
 */
export function getStyleLabel(styleId) {
  if (!isAllowedStyle(styleId)) {
    return null;
  }

  return STYLE_LABELS[styleId];
}

/**
 * 後端白名單與前端可用的風格 ID。
 */
export const allowedStyles = Object.freeze(
  Object.keys(STYLE_PROMPTS)
);

/**
 * 適合前端直接產生風格卡片的資料。
 *
 * 範例：
 *
 * styleOptions.forEach((style) => {
 *   console.log(style.id);
 *   console.log(style.label);
 *   console.log(style.isCartoon);
 * });
 */
export const styleOptions = Object.freeze(
  allowedStyles.map((id) =>
    Object.freeze({
      id,
      label: STYLE_LABELS[id],
      isCartoon: isCartoonStyle(id),
      isThreeD: isThreeDStyle(id)
    })
  )
);
